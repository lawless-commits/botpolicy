import { describe, expect, it } from "vitest";
import { isPublicAddress } from "./address.js";

describe("isPublicAddress", () => {
  it.each([
    "0.0.0.0", "0.1.2.3",
    "10.0.0.1", "10.255.255.255",
    "100.64.0.1", "100.127.255.255",
    "127.0.0.1", "127.8.9.10",
    "169.254.169.254",
    "172.16.0.1", "172.31.255.255",
    "192.0.0.8", "192.0.2.1",
    "192.168.1.1",
    "198.18.0.1", "198.19.255.255", "198.51.100.7", "203.0.113.9",
    "224.0.0.1", "239.255.255.255",
    "240.0.0.1", "255.255.255.255",
  ])("refuses IPv4 %s", (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each([
    "::", "::1",
    "fc00::1", "fd12:3456::1",
    "fe80::1", "febf::1",
    "ff02::1",
    "2001:db8::1",
    "::ffff:127.0.0.1", "::ffff:7f00:1", "::ffff:10.0.0.1", "::ffff:169.254.169.254",
    "::127.0.0.1",
    "64:ff9b::7f00:1", "64:ff9b::10.0.0.1", "64:ff9b:1::1",
    "2002:7f00:1::1", "2002:0a00:0001::1",
    "2001:0:4136:e378::1",
  ])("refuses IPv6 %s", (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each([
    "1.1.1.1", "8.8.8.8", "93.184.216.34", "172.32.0.1", "100.128.0.1", "198.20.0.1",
    "2606:4700:4700::1111", "2a00:1450:4001::200e",
    "::ffff:8.8.8.8", "64:ff9b::808:808", "2002:0808:0808::1",
  ])("allows public %s", (ip) => {
    expect(isPublicAddress(ip)).toBe(true);
  });

  it.each(["", "localhost", "999.1.1.1", "1.2.3", "::gg", "example.com"])(
    "refuses non-address %j",
    (ip) => {
      expect(isPublicAddress(ip)).toBe(false);
    },
  );
});
